// Third-party notices for what ships in Next Launcher (Phase 9).
//
//   node tools/licenses.mjs
//
// Writes:
//   ui/src/lib/licenses.json           summary for Settings → About (name, version, license)
//   src-tauri/THIRD-PARTY-NOTICES.txt  full license texts, bundled with the installer
//
// Rust: every crate reachable from `next-launcher` through normal (not dev/build) dependencies.
// UI: the production npm dependencies bundled into the frontend, plus the Inter font.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--filter-platform', 'x86_64-pc-windows-msvc'], { maxBuffer: 256 << 20 }).toString());
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const root = meta.packages.find((p) => p.name === 'next-launcher');
const workspace = new Set(meta.workspace_members);

const seen = new Set();
const stack = [root.id];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
  }
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)/i;
function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').trim() }));
}

const entries = [];
for (const id of seen) {
  if (workspace.has(id)) continue; // our own crates
  const p = byId.get(id);
  entries.push({
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? 'see license file' : 'unknown'),
    source: 'Rust crate',
    texts: licenseTexts(dirname(p.manifest_path)),
  });
}

// UI: production dependencies (bundled by Vite) and Svelte's runtime.
const uiPkg = JSON.parse(readFileSync('ui/package.json', 'utf8'));
for (const name of [...Object.keys(uiPkg.dependencies ?? {}), 'svelte']) {
  const dir = ['ui/node_modules', 'node_modules'].map((d) => join(d, name)).find((d) => existsSync(join(d, 'package.json')));
  if (!dir) continue;
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  entries.push({ name, version: pkg.version, license: pkg.license ?? 'unknown', source: 'npm package', texts: licenseTexts(dir) });
}
// The bundled Inter font (SIL Open Font License 1.1); its license ships next to the font files.
const ofl = 'ui/src/assets/fonts/Inter-OFL.txt';
entries.push({
  name: 'Inter (font)',
  version: '4',
  license: 'OFL-1.1',
  source: 'font',
  texts: existsSync(ofl) ? [{ file: 'Inter-OFL.txt', text: readFileSync(ofl, 'utf8').trim() }] : [],
});

entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

writeFileSync(
  'ui/src/lib/licenses.json',
  JSON.stringify(entries.map(({ name, version, license, source }) => ({ name, version, license, source }))) + '\n',
);

// Full notices: identical license texts are printed once and referenced.
const textIds = new Map();
const blocks = [];
const lines = [
  'Next Launcher: third-party notices',
  '',
  'Next Launcher includes the following open-source software. Each component is listed with its',
  'version and license; the license texts follow. Generated by tools/licenses.mjs.',
  '',
];
for (const e of entries) {
  const refs = e.texts.map((t) => {
    if (!textIds.has(t.text)) {
      textIds.set(t.text, `T${textIds.size + 1}`);
      blocks.push(`----- ${textIds.get(t.text)} (first seen in ${e.name} ${e.version}, ${t.file}) -----\n\n${t.text}\n`);
    }
    return textIds.get(t.text);
  });
  lines.push(`${e.name} ${e.version}  [${e.license}]${refs.length ? `  texts: ${refs.join(', ')}` : '  (license text from the SPDX identifier)'}`);
}
lines.push('', '', ...blocks);
writeFileSync('src-tauri/THIRD-PARTY-NOTICES.txt', lines.join('\n').replace(/\r\n/g, '\n'));

const missing = entries.filter((e) => e.texts.length === 0).length;
console.log(`${entries.length} components, ${textIds.size} distinct license texts, ${missing} identified by SPDX id only`);
